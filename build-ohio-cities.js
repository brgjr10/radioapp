'use strict';
/*
 * Regenerate ohio-cities.js from a US cities dataset.
 *
 * Usage:
 *   curl -fsSL -o /tmp/us_cities.csv \
 *     https://raw.githubusercontent.com/kelvins/US-Cities-Database/main/csv/us_cities.csv
 *   node build-ohio-cities.js /tmp/us_cities.csv
 *
 * Source: kelvins/US-Cities-Database (MIT). Columns:
 *   ID,STATE_CODE,STATE_NAME,CITY,COUNTY,LATITUDE,LONGITUDE
 *
 * Output ohio-cities.js sets window.OHIO_PLACES = [{ n, la, lo }, ...] with one
 * entry per Ohio city plus one per county (centroid = mean of its cities),
 * named "<county> county". app.js matches these names inside talkgroup titles.
 */

const fs = require('fs');

const src = process.argv[2] || '/tmp/us_cities.csv';
const raw = fs.readFileSync(src, 'utf8');

// Minimal CSV line parser (handles double-quoted fields with commas).
function parseLine(line) {
  const out = [];
  let cur = '', inQ = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQ) {
      if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; }
      else cur += c;
    } else {
      if (c === '"') inQ = true;
      else if (c === ',') { out.push(cur); cur = ''; }
      else cur += c;
    }
  }
  out.push(cur);
  return out;
}

const lines = raw.split(/\r?\n/);
const cities = new Map();          // cityName -> { la, lo }
const counties = new Map();        // countyName -> { latSum, lonSum, n }

for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line) continue;
  const f = parseLine(line);
  if (f[1] !== 'OH') continue;
  const city = (f[3] || '').trim();
  const county = (f[4] || '').trim();
  const la = parseFloat(f[5]);
  const lo = parseFloat(f[6]);
  if (!city || isNaN(la) || isNaN(lo)) continue;

  if (!cities.has(city)) cities.set(city, { la, lo });

  if (county) {
    const c = counties.get(county) || { latSum: 0, lonSum: 0, n: 0 };
    c.latSum += la; c.lonSum += lo; c.n++;
    counties.set(county, c);
  }
}

const places = [];
for (const [name, p] of cities) {
  places.push({ n: name, la: +p.la.toFixed(5), lo: +p.lo.toFixed(5) });
}
for (const [name, c] of counties) {
  places.push({
    n: name + ' County',
    la: +(c.latSum / c.n).toFixed(5),
    lo: +(c.lonSum / c.n).toFixed(5),
  });
}

places.sort((a, b) => a.n.localeCompare(b.n));

const header =
  '/* Auto-generated by build-ohio-cities.js — do not edit by hand.\n' +
  ' * Ohio cities + county centroids with coordinates, used to place calls on\n' +
  ' * the map by matching city/county names inside talkgroup titles.\n' +
  ' * Source: kelvins/US-Cities-Database (MIT). ' + cities.size + ' cities, ' +
  counties.size + ' counties.\n */\n';

const body = 'window.OHIO_PLACES = [\n' +
  places.map((p) => '  { n: ' + JSON.stringify(p.n) + ', la: ' + p.la + ', lo: ' + p.lo + ' }').join(',\n') +
  '\n];\n';

fs.writeFileSync('ohio-cities.js', header + body);
console.log('Wrote ohio-cities.js:', cities.size, 'cities +', counties.size, 'counties =', places.length, 'places');
